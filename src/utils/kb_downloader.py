#!/usr/bin/env python3
"""
知识库下载器
提供知识库完整数据的打包下载功能
"""

import os
import json
import zipfile
import io
from datetime import datetime
from typing import Optional, Dict, Any

def download_knowledge_base_custom(kb_name: str, kb_path: str, options: Dict[str, bool]) -> Optional[bytes]:
    """
    自定义下载知识库数据包
    
    Args:
        kb_name: 知识库名称
        kb_path: 知识库路径
        options: 下载选项字典
    
    Returns:
        压缩包的字节数据，失败返回None
    """
    try:
        if not os.path.exists(kb_path):
            return None
        
        # 创建内存中的ZIP文件
        zip_buffer = io.BytesIO()
        
        with zipfile.ZipFile(zip_buffer, 'w', zipfile.ZIP_DEFLATED) as zip_file:
            # 1. 添加知识库元数据（如果选择）
            if options.get('include_metadata', True):
                metadata = collect_kb_metadata(kb_name, kb_path)
                zip_file.writestr("metadata.json", json.dumps(metadata, indent=2, ensure_ascii=False))
            
            # 2. 添加向量数据库文件（如果选择）
            if options.get('include_vectors', True):
                add_vector_files(zip_file, kb_path)
            
            # 3. 添加源文档文件（如果选择）
            if options.get('include_docs', True):
                add_source_documents(zip_file, kb_path)
            
            # 4. 添加对话历史（如果选择）
            if options.get('include_history', False):
                add_chat_history(zip_file, kb_name)
            
            # 5. 添加配置文件（如果选择）
            if options.get('include_config', True):
                add_config_files(zip_file, kb_path)
            
            # 6. 添加统计信息（如果选择）
            if options.get('include_stats', True):
                add_statistics(zip_file, kb_path)
            
            # 7. 添加README说明文件
            readme_content = generate_readme(kb_name, options)
            zip_file.writestr("README.md", readme_content)
        
        zip_buffer.seek(0)
        return zip_buffer.getvalue()
        
    except Exception as e:
        print(f"下载知识库失败: {e}")
        return None

